//! Landing from an elytra glide, against BDS 1.26.52.3 traces (Dataminer `out/1.26.52/movement-traces.json`,
//! head 524dcbc: "elytra glide from 4 up at pitch 0, to landing and on", and the same at pitch 30).

use acacia_physics::test_world::{TestBlock, TestWorld};
use acacia_physics::{Input, PlayerState, tick};

/// A stone floor at y 199 and a ledge at y 203 to walk off, as the trace's setup fills them.
fn ground() -> TestWorld {
    let mut w = TestWorld::new();
    w.fill(Some(TestBlock::Stone), [50, 199, -30], [70, 199, 60]);
    w.fill(Some(TestBlock::Stone), [58, 203, -24], [62, 203, -18]);
    w
}

/// Feet each tick: forward held throughout, a jump press opening the glide on tick 22, the glide
/// held until the tick after the landing the server reports.
fn replay(pitch: f32, landing: usize, ticks: usize) -> Vec<[f32; 3]> {
    let w = ground();
    let mut st = PlayerState::new([60.5, 204.0, -20.5]);
    st.on_ground = true;
    st.equipment.elytra = true;
    (0..ticks)
        .map(|i| {
            let input = Input {
                move_vector: [0.0, 1.0],
                pitch: if i >= 22 { pitch } else { 0.0 },
                jump: i == 22,
                glide: (22..=landing).contains(&i),
                ..Input::default()
            };
            tick(&mut st, &input, &w);
            st.pos
        })
        .collect()
}

fn check(trace: &[[f32; 3]], ours: &[[f32; 3]]) {
    for (i, (t, o)) in trace.iter().zip(ours).enumerate() {
        let off = (0..3).map(|a| (t[a] - o[a]).abs()).fold(0.0, f32::max);
        assert!(off < 1e-4, "tick {i}: trace {t:?}, ours {o:?}");
    }
}

